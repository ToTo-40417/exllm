def variants(prompt, answer, n=1, cat='misc'):
    return [{'prompt':prompt,'answer':answer,'category':cat} for _ in range(n)]

def build():
    rows=[]
    # Greetings, deliberately many output variants so exact responses are not hard-coded.
    for _ in range(2500):
        p=R.choice(GREET_PROMPTS)
        if p.startswith('おはよう'): a=R.choice(MORNING)
        elif p=='こんばんは': a=R.choice(EVENING)
        else: a=R.choice(GREET_ANS)
        rows.append({'prompt':p,'answer':a,'category':'greeting'})
    for _ in range(1300): rows += variants(R.choice(IDENTITY_PROMPTS),R.choice(IDENTITY_ANS),cat='identity')
    for _ in range(900): rows += variants(R.choice(DEV_PROMPTS),R.choice(DEV_ANS),cat='developer')
    for _ in range(900): rows += variants(R.choice(CAP_PROMPTS),R.choice(CAP_ANS),cat='capability')
    for _ in range(900):
        p,a=R.choice(OFFLINE); rows += variants(p,a,cat='offline')
    for _ in range(1200):
        p,a=R.choice(POLITE); rows += variants(p,a,cat='polite')
    for x,d in TERMS.items():
        for q in TERM_Q:
            for _ in range(2): rows.append({'prompt':q.format(x=x),'answer':R.choice(TERM_A).format(d=d),'category':'definition'})
    for _ in range(1400):
        p,a=R.choice(FACTS); rows += variants(p,a,cat='fact')
    for _ in range(800):
        p,a=R.choice(SAFETY); rows += variants(p,a,cat='safety')
    for _ in range(700): rows += variants(R.choice(FALLBACK_PROMPTS),R.choice(FALLBACK_ANS),cat='fallback')
    for _ in range(1000):
        p,a=R.choice(CONV); rows += variants(p,a,cat='conversation')
    # arithmetic: diverse wording, exact generated answers. Keep bounded to what a 2M model can learn.
    add_q=['{a}+{b}は？','{a}たす{b}は？','{a} + {b} = ?','{a}と{b}を足すと？']
    sub_q=['{a}-{b}は？','{a}ひく{b}は？','{a} - {b} = ?']
    mul_q=['{a}×{b}は？','{a}かける{b}は？','{a} * {b} = ?']
    for _ in range(3500):
        op=R.choice(['+','-','*'])
        if op=='+':
            a,b=R.randint(0,20),R.randint(0,20); q=R.choice(add_q).format(a=a,b=b); ans=f'{a+b}です。'
        elif op=='-':
            a,b=R.randint(0,30),R.randint(0,20); q=R.choice(sub_q).format(a=a,b=b); ans=f'{a-b}です。'
        else:
            a,b=R.randint(0,10),R.randint(0,10); q=R.choice(mul_q).format(a=a,b=b); ans=f'{a*b}です。'
        rows.append({'prompt':q,'answer':ans,'category':'arithmetic'})
    # Character/encoding robustness examples.
    unicode_pairs=[
      ('「猫」って何？',TERMS['猫']),('ＡＩって何？','「ＡＩ」は全角表記です。AIは人工知能を意味します。'),
      ('絵文字🙂も読める？','UTF-8で表せる文字は入力できます。ただし、意味を正しく理解できるとは限りません。'),
      ('髙という字は読める？','入力として扱えますが、珍しい字の読みを必ず正しく答えられるわけではありません。'),
      ('カフェ☕','「カフェ」は飲み物や軽食を提供する店を指します。☕はコーヒーを表す絵文字です。'),
      ('半角ｶﾀｶﾅは？','半角カタカナもUTF-8の文字として入力できます。'),
    ]
    for _ in range(1000):
        p,a=R.choice(unicode_pairs); rows.append({'prompt':p,'answer':a,'category':'unicode'})
    R.shuffle(rows)
    return rows

def main(outdir):
    out=Path(outdir); out.mkdir(parents=True,exist_ok=True)
    rows=build()
    # Hold out 8% at random; dedicated challenge set is separate.
    n=int(len(rows)*0.92); train,valid=rows[:n],rows[n:]
    for name,part in [('train',train),('valid',valid)]:
        with (out/f'{name}.jsonl').open('w',encoding='utf-8') as f:
            for r in part: f.write(json.dumps(r,ensure_ascii=False)+'\n')
    print('rows',len(rows),'train',len(train),'valid',len(valid))
    from collections import Counter
    print(Counter(r['category'] for r in rows))

if __name__=='__main__':
    import sys; main(sys.argv[1] if len(sys.argv)>1 else 'data')
